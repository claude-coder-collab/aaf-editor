#!/usr/bin/env python3
"""Generate the built-in table of SMPTE label names from the SMPTE Labels register (ST 400).

Step 1 (`json`): the register XML -> model/smpte_labels.json. Reads `--xml PATH`, or downloads the published
                 register from registry.smpte-ra.org.
Step 2 (`cpp`):  model/smpte_labels.json -> libs/core/src/generated/smpte_labels.cpp.
`all` runs both; `check` verifies the committed C++ matches the committed JSON.

Labels are keyed by their AUID (the byte-swapped UL that AAF stores). The UL version byte (byte 8) is ignored
when matching, so it is zeroed in the sort key; for labels that differ only in that byte, the entry that is
not deprecated, then the one with the highest version, is kept.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = REPO_ROOT / "model" / "smpte_labels.json"
CPP_PATH = REPO_ROOT / "libs" / "core" / "src" / "generated" / "smpte_labels.cpp"
REGISTER_URL = "https://registry.smpte-ra.org/view/published/Labels.xml"
NAMESPACE = {"r": "http://www.smpte-ra.org/schemas/400/2012"}

Label = dict[str, Any]


def ul_bytes(urn: str) -> bytes:
    text = urn.removeprefix("urn:smpte:ul:").replace(".", "")
    if not re.fullmatch(r"[0-9a-fA-F]{32}", text):
        raise ValueError(f"not a UL: {urn}")
    return bytes.fromhex(text)


def auid_string(ul: bytes) -> str:
    """The AUID text form of a UL: UL bytes 8-15 become Data1-Data3, and bytes 0-7 Data4."""
    h = ul.hex()
    return f"{h[16:24]}-{h[24:28]}-{h[28:32]}-{h[0:4]}-{h[4:16]}"


def sort_key(ul: bytes) -> bytes:
    """The stored (little-endian) AUID bytes with the UL version byte zeroed, as compared in C++."""
    stored = ul[8:12][::-1] + ul[12:14][::-1] + ul[14:16][::-1] + ul[0:8]
    return stored[:15] + b"\x00"


def parse_register(xml: bytes) -> dict[str, Any]:
    root = ET.fromstring(xml)
    tag = re.search(rb"master_commit_tag=(\S+)", xml)
    best: dict[bytes, tuple[Label, bool, int]] = {}
    for entry in root.iterfind(".//r:Entry", NAMESPACE):
        urn = entry.findtext("r:UL", namespaces=NAMESPACE)
        name = (entry.findtext("r:Name", namespaces=NAMESPACE) or "").strip()
        if not urn or not name:
            continue
        ul = ul_bytes(urn)
        deprecated = (entry.findtext("r:IsDeprecated", namespaces=NAMESPACE) or "").strip() == "true"
        node = (entry.findtext("r:Kind", namespaces=NAMESPACE) or "").strip() == "NODE"
        key = sort_key(ul)
        candidate = ({"ul": ul.hex(), "name": " ".join(name.split()), "deprecated": deprecated, "node": node}, deprecated, ul[7])
        current = best.get(key)
        if current is None or (current[1], -current[2]) > (candidate[1], -candidate[2]):
            best[key] = candidate
    labels = [best[k][0] for k in sorted(best)]
    return {"source": {"url": REGISTER_URL, "version": tag.group(1).decode() if tag else None}, "labels": labels}


def dump_json(data: dict[str, Any]) -> str:
    """One label per line, so register updates give readable diffs."""
    lines = [f'{{"source": {json.dumps(data["source"])},', ' "labels": [']
    lines += [f"  {json.dumps(label)}," for label in data["labels"]]
    lines[-1] = lines[-1].rstrip(",")
    lines += [" ]", "}", ""]
    return "\n".join(lines)


def cpp_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def generate_cpp(data: dict[str, Any]) -> str:
    out = [
        "// Generated by tools/gen_labels.py from model/smpte_labels.json. Do not edit.",
        f"// Source data: SMPTE Labels register {data['source']['version']} (BSD-3-Clause, see model/NOTICE).",
        "",
        '#include "smpte_labels_table.hpp"',
        "",
        "namespace aaf::detail",
        "{",
        "",
        "using namespace aaf::literals;",
        "",
        "namespace",
        "{",
        "",
        "const SmpteLabel kLabels[] = {",
    ]
    for label in data["labels"]:
        auid = auid_string(bytes.fromhex(label["ul"]))
        out.append(f"    {{ {cpp_string(auid)}_auid, {cpp_string(label['name'])}, {str(label['deprecated']).lower()}, {str(label['node']).lower()} }},")
    out += [
        "};",
        "",
        "}",
        "",
        "auto smpteLabels() noexcept -> std::span<const SmpteLabel>",
        "{",
        "    return kLabels;",
        "}",
        "",
        "}",
        "",
    ]
    return "\n".join(out)


def load_xml(path: str | None) -> bytes:
    if path:
        return Path(path).read_bytes()
    with urllib.request.urlopen(REGISTER_URL, timeout=60) as response:
        return response.read()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("step", choices=("json", "cpp", "all", "check"), default="all", nargs="?")
    parser.add_argument("--xml", help="register XML file to read instead of downloading it")
    args = parser.parse_args(argv)

    if args.step in ("json", "all"):
        data = parse_register(load_xml(args.xml))
        JSON_PATH.write_text(dump_json(data), encoding="utf-8")
        print(f"wrote {JSON_PATH.relative_to(REPO_ROOT)}: {len(data['labels'])} labels")
    data = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    cpp = generate_cpp(data)
    if args.step == "check":
        if CPP_PATH.read_text(encoding="utf-8") != cpp:
            print(f"{CPP_PATH.relative_to(REPO_ROOT)} is out of date; run tools/gen_labels.py cpp", file=sys.stderr)
            return 1
        return 0
    if args.step in ("cpp", "all"):
        CPP_PATH.write_text(cpp, encoding="utf-8")
        print(f"wrote {CPP_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
