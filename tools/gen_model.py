#!/usr/bin/env python3
"""Generate the built-in AAF baseline metamodel from the pyaaf2 model tables.

Step 1 (`json`): pyaaf2 tables -> model/baseline.json (requires pyaaf2).
Step 2 (`cpp`):  model/baseline.json -> libs/core/src/generated/baseline_model.cpp.
`all` runs both; `check` verifies the committed C++ matches the committed JSON.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = REPO_ROOT / "model" / "baseline.json"
CPP_PATH = REPO_ROOT / "libs" / "core" / "src" / "generated" / "baseline_model.cpp"

Model = dict[str, list[dict[str, Any]]]


def load_pyaaf2() -> Model:
    from aaf2 import metadict
    from aaf2.model import classdefs as cd
    from aaf2.model import typedefs as td

    classes: list[dict[str, Any]] = []
    for table in (cd.classdefs, metadict.root_classes):
        for name, (auid, parent, concrete, props) in table.items():
            classes.append(
                {
                    "id": auid.lower(),
                    "name": name,
                    "parent": parent.lower() if parent else None,
                    "concrete": bool(concrete),
                    "properties": [
                        {"id": pid_auid.lower(), "name": pname, "pid": pid or 0, "type": ptype.lower(), "optional": bool(optional), "unique": bool(unique)}
                        for pname, (pid_auid, pid, ptype, optional, unique) in props.items()
                    ],
                }
            )

    types: list[dict[str, Any]] = []

    def add(name: str, auid: str, kind: str, **fields: Any) -> None:
        types.append({"id": auid.lower(), "name": name, "kind": kind, **fields})

    for name, (auid, size, signed) in td.ints.items():
        add(name, auid, "integer", size=size, signed=bool(signed))
    for name, (auid, element, values) in td.enums.items():
        add(name, auid, "enumeration", element=element.lower(), values=[[int(v), n] for v, n in sorted(values.items())])
    for name, (auid, fields) in td.records.items():
        add(name, auid, "record", fields=[[fname, ftype.lower()] for fname, ftype in fields])
    for name, (auid, element, count) in td.fixed_arrays.items():
        add(name, auid, "fixed_array", element=element.lower(), count=count)
    for name, (auid, element) in td.var_arrays.items():
        add(name, auid, "var_array", element=element.lower())
    for name, (auid, element) in td.renames.items():
        add(name, auid, "rename", element=element.lower())
    for name, (auid, element) in td.strings.items():
        add(name, auid, "string", element=element.lower())
    for name, auid in td.streams.items():
        add(name, auid, "stream")
    for name, auid in td.opaques.items():
        add(name, auid, "opaque")
    for name, (auid, values) in td.extenums.items():
        add(name, auid, "ext_enum", values=[[v.lower(), n] for v, n in sorted(values.items())])
    for name, auid in td.chars.items():
        add(name, auid, "character")
    for name, (auid, size) in td.generic_chars.items():
        add(name, auid, "generic_character", size=size)
    for name, auid in td.indirects.items():
        add(name, auid, "indirect")
    for name, (auid, element) in td.sets.items():
        add(name, auid, "set", element=element.lower())
    for table in (td.strongrefs, metadict.root_types):
        for name, (auid, ref_class) in table.items():
            add(name, auid, "strong_ref", ref_class=ref_class.lower())
    for name, (auid, ref_class, path) in td.weakrefs.items():
        add(name, auid, "weak_ref", ref_class=ref_class.lower(), path=[p.lower() for p in path])

    classes.sort(key=lambda c: c["id"])
    types.sort(key=lambda t: t["id"])
    return {"classes": classes, "types": types}


def cpp_string(value: str | None) -> str:
    return json.dumps(value or "")


def generate_cpp(model: Model) -> str:
    out: list[str] = [
        "// Generated by tools/gen_model.py from model/baseline.json. Do not edit.",
        "// Source data: pyaaf2 model tables (MIT licence, see model/NOTICE).",
        "",
        '#include "baseline_tables.hpp"',
        "",
        "namespace aaf::detail",
        "{",
        "",
        "namespace",
        "{",
        "",
    ]
    for i, c in enumerate(model["classes"]):
        if c["properties"]:
            out.append(f"constexpr GenProperty kClassProps{i}[] = {{")
            for p in c["properties"]:
                out.append(
                    f"    {{ {cpp_string(p['id'])}, {cpp_string(p['name'])}, {cpp_string(p['type'])}, {p['pid']:#06x}, "
                    f"{str(p['optional']).lower()}, {str(p['unique']).lower()} }},"
                )
            out.append("};")
    for i, t in enumerate(model["types"]):
        if t.get("fields"):
            out.append(f"constexpr GenNamed kTypeFields{i}[] = {{")
            out.extend(f"    {{ {cpp_string(n)}, {cpp_string(v)} }}," for n, v in t["fields"])
            out.append("};")
        if t["kind"] == "ext_enum" and t["values"]:
            out.append(f"constexpr GenNamed kTypeExtValues{i}[] = {{")
            out.extend(f"    {{ {cpp_string(n)}, {cpp_string(v)} }}," for v, n in t["values"])
            out.append("};")
        if t["kind"] == "enumeration" and t["values"]:
            out.append(f"constexpr GenEnumValue kTypeEnumValues{i}[] = {{")
            out.extend(f"    {{ {cpp_string(n)}, {v} }}," for v, n in t["values"])
            out.append("};")
        if t.get("path"):
            out.append(f"constexpr std::string_view kTypePath{i}[] = {{")
            out.extend(f"    {cpp_string(p)}," for p in t["path"])
            out.append("};")
    out += ["", "constexpr GenClass kClasses[] = {"]
    for i, c in enumerate(model["classes"]):
        props = f"kClassProps{i}" if c["properties"] else "{}"
        out.append(f"    {{ {cpp_string(c['id'])}, {cpp_string(c['name'])}, {cpp_string(c['parent'])}, {str(c['concrete']).lower()}, {props} }},")
    out += ["};", "", "constexpr GenType kTypes[] = {"]
    for i, t in enumerate(model["types"]):
        fields = f"kTypeFields{i}" if t.get("fields") else "{}"
        ext_values = f"kTypeExtValues{i}" if t["kind"] == "ext_enum" and t["values"] else "{}"
        enum_values = f"kTypeEnumValues{i}" if t["kind"] == "enumeration" and t["values"] else "{}"
        path = f"kTypePath{i}" if t.get("path") else "{}"
        element = t.get("element") or t.get("ref_class")
        out.append(
            f"    {{ {cpp_string(t['id'])}, {cpp_string(t['name'])}, {cpp_string(element)}, "
            f"{fields}, {enum_values}, {ext_values}, {path}, "
            f"{t.get('count', 0)}, GenKind::{t['kind']}, {t.get('size', 0)}, {str(t.get('signed', False)).lower()} }},"
        )
    out += [
        "};",
        "",
        "}",
        "",
        "auto baselineClasses() noexcept -> std::span<const GenClass>",
        "{",
        "    return kClasses;",
        "}",
        "",
        "auto baselineTypes() noexcept -> std::span<const GenType>",
        "{",
        "    return kTypes;",
        "}",
        "",
        "}",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("step", choices=("json", "cpp", "all", "check"), default="all", nargs="?")
    args = parser.parse_args(argv)

    if args.step in ("json", "all"):
        JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
        JSON_PATH.write_text(json.dumps(load_pyaaf2(), indent=1) + "\n", encoding="utf-8")
    model = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    cpp = generate_cpp(model)
    if args.step == "check":
        if CPP_PATH.read_text(encoding="utf-8") != cpp:
            print(f"{CPP_PATH} is out of date; run tools/gen_model.py cpp", file=sys.stderr)
            return 1
        return 0
    if args.step in ("cpp", "all"):
        CPP_PATH.parent.mkdir(parents=True, exist_ok=True)
        CPP_PATH.write_text(cpp, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
